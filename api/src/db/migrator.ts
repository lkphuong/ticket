import { readdir, readFile } from 'node:fs/promises'
import { join } from 'node:path'

export interface SqlExecutor {
  exec(sql: string): Promise<unknown>
}

// Helper safely parsing row arrays across PGlite and standard Postgres clients
function extractRows(rawResult: unknown): unknown[] {
  if (Array.isArray(rawResult)) {
    // PGlite exec returns array of statement results: [{ rows: [...] }]
    if (rawResult.length > 0 && typeof rawResult[0] === 'object' && rawResult[0] !== null && 'rows' in rawResult[0]) {
      return (rawResult[0] as { rows: unknown[] }).rows
    }
    return rawResult
  }
  if (rawResult && typeof rawResult === 'object' && 'rows' in rawResult) {
    return (rawResult as { rows: unknown[] }).rows
  }
  return []
}

// Executes database migration scripts sequentially against target database connection
export async function runMigrations(executor: SqlExecutor, migrationsDir?: string): Promise<string[]> {
  const resolvedDir = migrationsDir ?? join(import.meta.dir, 'migrations')

  // Ensure migration tracking table exists to maintain execution idempotency
  await executor.exec(`
    CREATE TABLE IF NOT EXISTS "__drizzle_migrations" (
      id SERIAL PRIMARY KEY,
      hash TEXT NOT NULL UNIQUE,
      created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
    );
  `)

  const files = await readdir(resolvedDir)
  const sqlFiles = files.filter((f) => f.endsWith('.sql')).sort()
  const appliedMigrations: string[] = []

  for (const file of sqlFiles) {
    const filePath = join(resolvedDir, file)
    const content = await readFile(filePath, 'utf-8')

    // Check if migration has already been recorded
    const checkSql = `SELECT id FROM "__drizzle_migrations" WHERE hash = '${file}';`
    const rawResult = await executor.exec(checkSql)
    const rows = extractRows(rawResult)
    if (rows.length > 0) {
      continue
    }

    // Split statements safely across breakpoint delimiters generated by Drizzle Kit
    const statements = content
      .split('--> statement-breakpoint')
      .map((statement) => statement.trim())
      .filter((statement) => statement.length > 0)

    for (const statement of statements) {
      await executor.exec(statement)
    }

    // Record completed migration step
    await executor.exec(`INSERT INTO "__drizzle_migrations" (hash) VALUES ('${file}');`)
    appliedMigrations.push(file)
  }

  return appliedMigrations
}
